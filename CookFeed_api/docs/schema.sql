-- Cookfeed reference schema (PostgreSQL 16+).
-- This is a hand-written, readable equivalent of what `dotnet ef migrations add InitialCreate`
-- generates from CookfeedDbContext. The EF migration is the source of truth for deployment;
-- this file exists so the schema can be read without opening C#.
--
-- Revision after Assignment 2 feedback (see DesignDocument.md §3 "Marketplace business rules"):
--   * recipes.visibility            — Public recipes are in the free feed; ProductOnly recipes are reachable only
--                                     through a purchased product.
--   * product_recipes               — surrogate key so a meal plan can schedule the same recipe on more than one day.
--   * order_item_recipes            — snapshot of a product's bundle at checkout; entitlements read this, not the
--                                     live bundle, so a creator editing a product cannot take back what was bought.
--   * trg_saved_recipes_save_count  — recipes.save_count is maintained by the database, including on cascaded
--                                     deletes and during seeding.
--   * trg_*_refuse_self_purchase    — a creator cannot put their own product in a cart or an order.
--   * trg_user_roles_admin_only     — an Admin account holds no other role (admins are operational only).
--   * trg_*_product_only            — a product sells only ProductOnly recipes, so nothing a buyer pays for is
--                                     also free to save (added after Project Deliverable 2's review).
--   * admin moderation (§3.8)       — reviews.hidden_at, creator_profiles.suspended_at, and the admin_actions
--                                     audit table, which only an Admin account may write to.

CREATE TABLE users (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         varchar(254) NOT NULL,
    display_name  varchar(80)  NOT NULL,
    password_hash varchar(255) NOT NULL,
    created_at    timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ix_users_email ON users (email);

CREATE TABLE roles (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(40) NOT NULL                              -- HomeCook | Creator | Admin
);
CREATE UNIQUE INDEX ix_roles_name ON roles (name);

-- Role semantics (DesignDocument.md §3):
--   HomeCook  may save recipes, keep a cart, place orders, plan meals, write reviews. Granted to every ordinary
--             account at sign-up and to every creator, so a creator shops like anyone else.
--   Creator   may publish recipes and sell products. Always held together with HomeCook.
--   Admin     operational only: never buys, saves or sells. Never held together with another role (enforced below).
CREATE TABLE user_roles (
    user_id    integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role_id    integer NOT NULL REFERENCES roles (id) ON DELETE RESTRICT,
    granted_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, role_id)
);
CREATE INDEX ix_user_roles_role_id ON user_roles (role_id);

CREATE TABLE creator_profiles (
    user_id     integer PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,   -- shared PK: 1:1
    handle      varchar(40) NOT NULL,
    bio         varchar(1000),
    avatar_url  varchar(500),
    is_verified boolean NOT NULL,
    suspended_at timestamptz,                             -- set by an admin; products not for sale while set (§3.8)
    CONSTRAINT ck_creator_profiles_handle_slug CHECK (handle ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$')
);
CREATE UNIQUE INDEX ix_creator_profiles_handle ON creator_profiles (handle);

CREATE TABLE recipes (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_id    integer NOT NULL REFERENCES creator_profiles (user_id) ON DELETE CASCADE,
    title         varchar(120) NOT NULL,
    description   varchar(2000),
    video_url     varchar(500) NOT NULL,
    thumbnail_url varchar(500),
    servings      integer NOT NULL,
    prep_minutes  integer,
    cook_minutes  integer,
    is_published  boolean NOT NULL,                     -- the creator has finished it (draft vs live)
    visibility    varchar(12) NOT NULL DEFAULT 'Public', -- who may see it: 'Public' (free feed) | 'ProductOnly' (buyers)
    created_at    timestamptz NOT NULL DEFAULT now(),
    published_at  timestamptz,
    save_count    integer NOT NULL DEFAULT 0,          -- denormalized counter maintained by trigger, see design doc §6
    CONSTRAINT ck_recipes_servings_positive    CHECK (servings > 0),
    CONSTRAINT ck_recipes_published_has_date   CHECK (is_published = false OR published_at IS NOT NULL),
    CONSTRAINT ck_recipes_visibility           CHECK (visibility IN ('Public', 'ProductOnly'))
);
CREATE INDEX ix_recipes_creator_id                           ON recipes (creator_id);
CREATE INDEX ix_recipes_is_published_visibility_published_at ON recipes (is_published, visibility, published_at DESC);
CREATE INDEX ix_recipes_is_published_visibility_save_count   ON recipes (is_published, visibility, save_count DESC);

CREATE TABLE recipe_steps (
    id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id               integer NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
    step_number             integer NOT NULL,
    instruction             varchar(2000) NOT NULL,
    video_timestamp_seconds integer,
    duration_minutes        integer,
    CONSTRAINT ck_recipe_steps_number_positive CHECK (step_number > 0)
);
CREATE UNIQUE INDEX ix_recipe_steps_recipe_id_step_number ON recipe_steps (recipe_id, step_number);

CREATE TABLE units (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           varchar(40) NOT NULL,
    abbreviation   varchar(10) NOT NULL,
    category       varchar(10) NOT NULL,               -- 'Volume' | 'Mass' | 'Count'
    to_base_factor numeric(12,6) NOT NULL,             -- to ml / g / 1
    is_metric      boolean NOT NULL,
    CONSTRAINT ck_units_factor_positive CHECK (to_base_factor > 0)
);
CREATE UNIQUE INDEX ix_units_name         ON units (name);
CREATE UNIQUE INDEX ix_units_abbreviation ON units (abbreviation);

CREATE TABLE ingredients (
    id                         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                       varchar(80) NOT NULL,   -- canonical, lower-case
    category                   varchar(20) NOT NULL,   -- aisle grouping
    density_g_per_ml           numeric(8,4),           -- enables Volume <-> Mass conversion
    preferred_shopping_unit_id integer REFERENCES units (id) ON DELETE SET NULL,   -- also decides conversion direction, §7.4
    CONSTRAINT ck_ingredients_density_positive CHECK (density_g_per_ml IS NULL OR density_g_per_ml > 0)
);
CREATE UNIQUE INDEX ix_ingredients_name ON ingredients (name);
CREATE INDEX ix_ingredients_preferred_shopping_unit_id ON ingredients (preferred_shopping_unit_id);

CREATE TABLE recipe_ingredients (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id     integer NOT NULL REFERENCES recipes (id)     ON DELETE CASCADE,
    ingredient_id integer NOT NULL REFERENCES ingredients (id) ON DELETE RESTRICT,
    unit_id       integer NOT NULL REFERENCES units (id)       ON DELETE RESTRICT,
    quantity      numeric(10,3) NOT NULL,
    display_text  varchar(120),                        -- creator's wording, display only
    preparation   varchar(80),
    sort_order    integer NOT NULL,
    is_optional   boolean NOT NULL,
    CONSTRAINT ck_recipe_ingredients_quantity_positive CHECK (quantity > 0)
);
CREATE INDEX ix_recipe_ingredients_recipe_id_sort_order ON recipe_ingredients (recipe_id, sort_order);
CREATE INDEX ix_recipe_ingredients_ingredient_id        ON recipe_ingredients (ingredient_id);
CREATE INDEX ix_recipe_ingredients_unit_id              ON recipe_ingredients (unit_id);

CREATE TABLE saved_recipes (
    user_id   integer NOT NULL REFERENCES users (id)   ON DELETE CASCADE,
    recipe_id integer NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
    saved_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, recipe_id)
);
CREATE INDEX ix_saved_recipes_recipe_id ON saved_recipes (recipe_id);

CREATE TABLE meal_plans (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name       varchar(80) NOT NULL,
    week_start date NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ix_meal_plans_user_id_week_start ON meal_plans (user_id, week_start);

CREATE TABLE meal_plan_entries (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_plan_id      integer NOT NULL REFERENCES meal_plans (id) ON DELETE CASCADE,
    recipe_id         integer NOT NULL REFERENCES recipes (id)    ON DELETE CASCADE,
    planned_date      date NOT NULL,
    slot              varchar(10) NOT NULL,              -- Breakfast | Lunch | Dinner | Snack
    servings_override integer,
    CONSTRAINT ck_meal_plan_entries_servings_positive CHECK (servings_override IS NULL OR servings_override > 0)
);
CREATE INDEX ix_meal_plan_entries_meal_plan_id_planned_date_slot ON meal_plan_entries (meal_plan_id, planned_date, slot);
CREATE INDEX ix_meal_plan_entries_recipe_id ON meal_plan_entries (recipe_id);

CREATE TABLE products (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_id      integer NOT NULL REFERENCES creator_profiles (user_id) ON DELETE CASCADE,
    type            varchar(20) NOT NULL,                -- RecipeCollection | MealPlan
    title           varchar(120) NOT NULL,
    description     varchar(2000),
    cover_image_url varchar(500),
    price_cents     integer NOT NULL,
    currency        varchar(3) NOT NULL,
    is_active       boolean NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_products_price_nonnegative CHECK (price_cents >= 0)
);
CREATE INDEX ix_products_creator_id_is_active ON products (creator_id, is_active);

-- The live contents of a product. A meal plan may schedule the same recipe on several days (overnight oats on
-- Monday and Thursday), so the key is a surrogate id rather than (product_id, recipe_id). The one uniqueness rule
-- that remains is "a recipe appears at most once per (product, day, slot)"; for a collection day_offset and slot
-- are NULL, and NULLS NOT DISTINCT makes that collapse to "once per product".
CREATE TABLE product_recipes (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id integer NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    recipe_id  integer NOT NULL REFERENCES recipes (id)  ON DELETE RESTRICT,
    sort_order integer NOT NULL,
    day_offset integer,                                  -- 0..6 for MealPlan products, NULL for collections
    slot       varchar(10),                              -- Breakfast | Lunch | Dinner | Snack, NULL for collections
    CONSTRAINT ck_product_recipes_day_offset_range CHECK (day_offset IS NULL OR (day_offset BETWEEN 0 AND 6)),
    CONSTRAINT ck_product_recipes_placement_pair   CHECK ((day_offset IS NULL) = (slot IS NULL))
);
CREATE UNIQUE INDEX ix_product_recipes_product_id_recipe_id_day_offset_slot
    ON product_recipes (product_id, recipe_id, day_offset, slot) NULLS NOT DISTINCT;
CREATE INDEX ix_product_recipes_product_id_sort_order ON product_recipes (product_id, sort_order);
CREATE INDEX ix_product_recipes_recipe_id             ON product_recipes (recipe_id);

CREATE TABLE cart_items (
    user_id    integer NOT NULL REFERENCES users (id)    ON DELETE CASCADE,
    product_id integer NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    added_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, product_id)
);
CREATE INDEX ix_cart_items_product_id ON cart_items (product_id);

CREATE TABLE orders (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           integer NOT NULL REFERENCES users (id) ON DELETE RESTRICT,   -- never lose financial history
    status            varchar(12) NOT NULL,              -- Pending | Paid | Refunded | Cancelled
    placed_at         timestamptz NOT NULL DEFAULT now(),
    paid_at           timestamptz,
    total_cents       integer NOT NULL,                  -- denormalized, see design doc §6
    currency          varchar(3) NOT NULL,
    payment_reference varchar(100),
    CONSTRAINT ck_orders_total_nonnegative CHECK (total_cents >= 0)
);
CREATE INDEX ix_orders_user_id_placed_at ON orders (user_id, placed_at DESC);

CREATE TABLE order_items (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         integer NOT NULL REFERENCES orders (id)   ON DELETE CASCADE,
    product_id       integer NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
    creator_id       integer NOT NULL,                   -- snapshot of products.creator_id at checkout
    product_title    varchar(120) NOT NULL,              -- snapshot
    unit_price_cents integer NOT NULL,                   -- snapshot
    CONSTRAINT ck_order_items_price_nonnegative CHECK (unit_price_cents >= 0)
);
CREATE UNIQUE INDEX ix_order_items_order_id_product_id ON order_items (order_id, product_id);
CREATE INDEX ix_order_items_product_id ON order_items (product_id);
CREATE INDEX ix_order_items_creator_id ON order_items (creator_id);

-- Snapshot of product_recipes taken at checkout, one row per recipe in the bundle as it was that day.
-- This is what a buyer is entitled to. A creator may later add or remove recipes from the live product;
-- that changes what the *next* buyer gets and never what an earlier buyer already has.
CREATE TABLE order_item_recipes (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id integer NOT NULL REFERENCES order_items (id) ON DELETE CASCADE,
    recipe_id     integer NOT NULL REFERENCES recipes (id)     ON DELETE RESTRICT,   -- a sold recipe cannot be deleted
    sort_order    integer NOT NULL,
    day_offset    integer,
    slot          varchar(10),
    CONSTRAINT ck_order_item_recipes_day_offset_range CHECK (day_offset IS NULL OR (day_offset BETWEEN 0 AND 6)),
    CONSTRAINT ck_order_item_recipes_placement_pair   CHECK ((day_offset IS NULL) = (slot IS NULL))
);
CREATE UNIQUE INDEX ix_order_item_recipes_order_item_id_recipe_id_day_offset_slot
    ON order_item_recipes (order_item_id, recipe_id, day_offset, slot) NULLS NOT DISTINCT;
CREATE INDEX ix_order_item_recipes_recipe_id ON order_item_recipes (recipe_id);

-- Added for Assignment 3: customer reviews of products (the prototype's Reviews page).
-- The reviewer's name is users.display_name, joined in; it is not copied here.
-- A review requires a Paid order item for the product by the same user (API rule); because a creator can never
-- buy their own product, a creator can never review their own product either.
CREATE TABLE reviews (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id integer NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    user_id    integer NOT NULL REFERENCES users (id)    ON DELETE CASCADE,
    rating     smallint NOT NULL,                        -- 1..5 stars
    recommends boolean NOT NULL,
    body       varchar(2000) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    hidden_at  timestamptz,                              -- set by an admin; shown only to admins while set (§3.8)
    CONSTRAINT ck_reviews_rating_range CHECK (rating BETWEEN 1 AND 5)
);
CREATE UNIQUE INDEX ix_reviews_product_id_user_id    ON reviews (product_id, user_id);   -- one review per user per product
CREATE INDEX        ix_reviews_product_id_created_at ON reviews (product_id, created_at DESC);
CREATE INDEX        ix_reviews_user_id               ON reviews (user_id);

-- What an admin did to somebody else's row (§3.8): hid a review, suspended a creator, retired a product, refunded
-- an order. Written in the same transaction as the change it records. The admin account cannot be deleted while
-- its actions exist, so the trail outlives the account.
CREATE TABLE admin_actions (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_user_id integer NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    action        varchar(40) NOT NULL,                  -- HideReview | RestoreReview | SuspendCreator | ... (API-defined)
    target_table  varchar(40) NOT NULL,                  -- reviews | creator_profiles | products | recipes | orders
    target_id     integer NOT NULL,
    note          varchar(500),
    created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_admin_actions_admin_user_id_created_at ON admin_actions (admin_user_id, created_at DESC);
CREATE INDEX ix_admin_actions_target_table_target_id   ON admin_actions (target_table, target_id);

-- ---------------------------------------------------------------------------------------------------------------
-- Triggers: rules about which rows may exist, enforced regardless of which caller writes them.
-- Authorization rules (who may perform an action, e.g. "saving requires HomeCook") are not here; they belong to
-- the API's authorization layer, see DesignDocument.md §3.
-- ---------------------------------------------------------------------------------------------------------------

-- recipes.save_count == COUNT(*) FROM saved_recipes WHERE recipe_id = recipes.id, always.
-- A row-level trigger fires for ordinary saves and unsaves, for the rows the seed inserts, and for the rows
-- removed by ON DELETE CASCADE when an account is hard-deleted; the counter cannot drift from the save rows.
CREATE FUNCTION trg_saved_recipes_save_count() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        UPDATE recipes SET save_count = save_count + 1 WHERE id = NEW.recipe_id;
        RETURN NEW;
    ELSE
        UPDATE recipes SET save_count = save_count - 1 WHERE id = OLD.recipe_id;
        RETURN OLD;
    END IF;
END $$;
CREATE TRIGGER saved_recipes_save_count
    AFTER INSERT OR DELETE ON saved_recipes
    FOR EACH ROW EXECUTE FUNCTION trg_saved_recipes_save_count();

-- A creator cannot buy their own product: refused at the cart and again at the order line, so neither the API
-- nor a direct SQL caller can create the row.
CREATE FUNCTION trg_cart_items_refuse_self_purchase() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM products p WHERE p.id = NEW.product_id AND p.creator_id = NEW.user_id) THEN
        RAISE EXCEPTION 'A creator cannot add their own product (id %) to their cart', NEW.product_id
            USING ERRCODE = 'check_violation', CONSTRAINT = 'ck_cart_items_no_self_purchase';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER cart_items_refuse_self_purchase
    BEFORE INSERT OR UPDATE ON cart_items
    FOR EACH ROW EXECUTE FUNCTION trg_cart_items_refuse_self_purchase();

CREATE FUNCTION trg_order_items_refuse_self_purchase() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1
               FROM orders o JOIN products p ON p.id = NEW.product_id
               WHERE o.id = NEW.order_id AND p.creator_id = o.user_id) THEN
        RAISE EXCEPTION 'A creator cannot buy their own product (id %)', NEW.product_id
            USING ERRCODE = 'check_violation', CONSTRAINT = 'ck_order_items_no_self_purchase';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER order_items_refuse_self_purchase
    BEFORE INSERT OR UPDATE ON order_items
    FOR EACH ROW EXECUTE FUNCTION trg_order_items_refuse_self_purchase();

-- Admins are operational only. An account holding Admin holds no other role, and an account holding another
-- role cannot be granted Admin; promote by creating a separate admin account.
CREATE FUNCTION trg_user_roles_admin_only() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    new_role  varchar(40);
    conflicts integer;
BEGIN
    SELECT name INTO new_role FROM roles WHERE id = NEW.role_id;
    SELECT COUNT(*) INTO conflicts
    FROM user_roles ur JOIN roles r ON r.id = ur.role_id
    WHERE ur.user_id = NEW.user_id AND ur.role_id <> NEW.role_id
      AND (new_role = 'Admin' OR r.name = 'Admin');
    IF conflicts > 0 THEN
        RAISE EXCEPTION 'User % cannot hold Admin together with another role', NEW.user_id
            USING ERRCODE = 'check_violation', CONSTRAINT = 'ck_user_roles_admin_only';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER user_roles_admin_only
    BEFORE INSERT OR UPDATE ON user_roles
    FOR EACH ROW EXECUTE FUNCTION trg_user_roles_admin_only();

-- A product sells only ProductOnly recipes: nothing a buyer pays for is also free to save from the feed
-- (DesignDocument.md §3.3). Refused when a Public recipe is put in a product, and when a recipe that is in a
-- product is made Public. To give a recipe away, the creator takes it out of their products first; buyers keep
-- it through their order snapshots.
CREATE FUNCTION trg_product_recipes_product_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM recipes r WHERE r.id = NEW.recipe_id AND r.visibility = 'Public') THEN
        RAISE EXCEPTION 'Recipe % is Public; only ProductOnly recipes can be put in a product', NEW.recipe_id
            USING ERRCODE = 'check_violation', CONSTRAINT = 'ck_product_recipes_product_only';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER product_recipes_product_only
    BEFORE INSERT OR UPDATE ON product_recipes
    FOR EACH ROW EXECUTE FUNCTION trg_product_recipes_product_only();

CREATE FUNCTION trg_recipes_in_product_product_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.visibility = 'Public' AND EXISTS (SELECT 1 FROM product_recipes pr WHERE pr.recipe_id = NEW.id) THEN
        RAISE EXCEPTION 'Recipe % is in a product, so it cannot be made Public', NEW.id
            USING ERRCODE = 'check_violation', CONSTRAINT = 'ck_recipes_in_product_product_only';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER recipes_in_product_product_only
    BEFORE UPDATE OF visibility ON recipes
    FOR EACH ROW EXECUTE FUNCTION trg_recipes_in_product_product_only();

-- Only an Admin account writes the audit trail (§3.8).
CREATE FUNCTION trg_admin_actions_admin_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM user_roles ur JOIN roles r ON r.id = ur.role_id
                   WHERE ur.user_id = NEW.admin_user_id AND r.name = 'Admin') THEN
        RAISE EXCEPTION 'User % is not an admin, so cannot write admin_actions', NEW.admin_user_id
            USING ERRCODE = 'check_violation', CONSTRAINT = 'ck_admin_actions_admin_only';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER admin_actions_admin_only
    BEFORE INSERT OR UPDATE ON admin_actions
    FOR EACH ROW EXECUTE FUNCTION trg_admin_actions_admin_only();
