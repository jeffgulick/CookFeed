namespace Cookfeed.IntegrationTests.Support;

/// <summary>
/// Describes a database's structure by asking PostgreSQL's own catalog, one line per object, so two
/// databases built different ways (EF Core migration vs. <c>schema.sql</c>) can be compared line by line.
/// PostgreSQL prints every definition in its own normalised form, so formatting differences between the
/// two sources disappear and only real differences remain.
/// </summary>
public static class SchemaCatalog
{
    /// <summary>EF Core's own bookkeeping table, which <c>schema.sql</c> does not have.</summary>
    private const string NotEfHistory = "'__EFMigrationsHistory'";

    public static Task<List<string>> TablesAsync(string connectionString) => Sql.QueryLinesAsync(connectionString, $"""
        SELECT c.relname
        FROM pg_class c
        WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r' AND c.relname <> {NotEfHistory}
        ORDER BY 1
        """);

    /// <summary>table | column | type | NULL or NOT NULL | default | identity</summary>
    public static Task<List<string>> ColumnsAsync(string connectionString) => Sql.QueryLinesAsync(connectionString, $"""
        SELECT c.relname,
               a.attname,
               format_type(a.atttypid, a.atttypmod),
               CASE WHEN a.attnotnull THEN 'NOT NULL' ELSE 'NULL' END,
               COALESCE(pg_get_expr(d.adbin, d.adrelid), '(no default)'),
               CASE a.attidentity WHEN 'd' THEN 'GENERATED BY DEFAULT AS IDENTITY'
                                  WHEN 'a' THEN 'GENERATED ALWAYS AS IDENTITY'
                                  ELSE '(not identity)' END
        FROM pg_attribute a
        JOIN pg_class c ON c.oid = a.attrelid
        LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r' AND c.relname <> {NotEfHistory}
          AND a.attnum > 0 AND NOT a.attisdropped
        ORDER BY 1, 2
        """);

    /// <summary>
    /// Every index except the ones PostgreSQL creates for primary keys (those are compared as constraints).
    /// The line is PostgreSQL's own CREATE INDEX statement, so the name, columns, sort order, uniqueness and
    /// NULLS NOT DISTINCT are all compared.
    /// </summary>
    public static Task<List<string>> IndexesAsync(string connectionString) => Sql.QueryLinesAsync(connectionString, $"""
        SELECT pg_get_indexdef(i.indexrelid)
        FROM pg_index i
        JOIN pg_class t ON t.oid = i.indrelid
        WHERE t.relnamespace = 'public'::regnamespace AND t.relname <> {NotEfHistory}
          AND NOT i.indisprimary
        ORDER BY 1
        """);

    /// <summary>
    /// Check constraints, compared by name and definition: the names (<c>ck_…</c>) are part of the design,
    /// and the API will map a violated one to an error message by its name.
    /// </summary>
    public static Task<List<string>> CheckConstraintsAsync(string connectionString) => Sql.QueryLinesAsync(connectionString, $"""
        SELECT t.relname, c.conname, pg_get_constraintdef(c.oid)
        FROM pg_constraint c
        JOIN pg_class t ON t.oid = c.conrelid
        WHERE c.connamespace = 'public'::regnamespace AND c.contype = 'c'
        ORDER BY 1, 2
        """);

    /// <summary>
    /// Primary and foreign keys, compared by table and definition (columns, referenced table, ON DELETE rule)
    /// but not by name. <c>schema.sql</c> lets PostgreSQL name them (<c>users_pkey</c>,
    /// <c>user_roles_user_id_fkey</c>) and EF Core names them its own way (<c>pk_users</c>,
    /// <c>fk_user_roles_users_user_id</c>); nothing in the design depends on those names.
    /// </summary>
    public static Task<List<string>> KeysAsync(string connectionString) => Sql.QueryLinesAsync(connectionString, $"""
        SELECT t.relname, pg_get_constraintdef(c.oid)
        FROM pg_constraint c
        JOIN pg_class t ON t.oid = c.conrelid
        WHERE c.connamespace = 'public'::regnamespace AND c.contype IN ('p', 'f')
          AND t.relname <> {NotEfHistory}
        ORDER BY 1, 2
        """);

    /// <summary>The trigger functions' full source.</summary>
    public static Task<List<string>> FunctionsAsync(string connectionString) => Sql.QueryLinesAsync(connectionString, """
        SELECT pg_get_functiondef(p.oid)
        FROM pg_proc p
        WHERE p.pronamespace = 'public'::regnamespace
        ORDER BY p.proname
        """);

    /// <summary>The triggers themselves: table, timing, events and the function each one calls.</summary>
    public static Task<List<string>> TriggersAsync(string connectionString) => Sql.QueryLinesAsync(connectionString, """
        SELECT pg_get_triggerdef(t.oid)
        FROM pg_trigger t
        JOIN pg_class c ON c.oid = t.tgrelid
        WHERE c.relnamespace = 'public'::regnamespace AND NOT t.tgisinternal
        ORDER BY 1
        """);
}
